import puppeteer from 'puppeteer-core';
const base = process.argv[2] || 'http://localhost:8000/';
const w = +(process.argv[3] || 390);
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const page = await browser.newPage();
await page.setViewport({ width: w, height: 844, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('requestfailed', (r) => errors.push('failed: ' + r.url()));
page.on('response', (r) => { if (r.status() >= 400) errors.push(r.status() + ' ' + r.url()); });
await page.goto(base + 'games.php', { waitUntil: 'networkidle0' });
await sleep(800);
console.log(JSON.stringify(await page.evaluate(() => ({ scrollW: document.documentElement.scrollWidth, innerW: window.innerWidth, canvas: document.querySelector('.n8-canvas').style.width }))));
const st = await page.$('.n8-stage');
await st.scrollIntoView(); await sleep(300);
const ov = await page.$('.n8-overlay'); await ov.tap(); await sleep(2600);
await (await page.$('.n8-a')).tap(); await sleep(600);
await (await page.$('.n8-a')).tap(); await sleep(600);
await page.screenshot({ path: 'tests/shots/phone-' + w + '.png' });
console.log(errors.join('\n') || 'no errors');
await browser.close();
